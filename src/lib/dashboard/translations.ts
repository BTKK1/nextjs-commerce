export function translateDashboardText(input: string, locale: DashboardTranslationLocale): string {
  if (locale === "en") return input;
  const text = input.trim();
  if (!text) return input;
  const leading = input.slice(0, input.length - input.trimStart().length);
  const trailing = input.slice(input.trimEnd().length);
  const exact = dashboardArabic[text];
  if (exact) return `${leading}${exact}${trailing}`;
  for (const [pattern, formatter] of dynamicArabic) {
    const match = text.match(pattern);
    if (match) return `${leading}${formatter(...match.slice(1))}${trailing}`;
  }
  return input;
}
